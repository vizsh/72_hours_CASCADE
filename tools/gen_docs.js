// Generates the reference documents in docs/reference/ from the geodata and engine runs, so every
// table (facilities, links, districts, results, catalogues, messages) matches the code exactly.
//   node tools/gen_docs.js            (about 3-4 minutes: every city x scenario, planners, red team)
const fs = require('fs'), path = require('path'), vm = require('vm');
const ROOT = path.resolve(__dirname, '..');
global.window = global; global.self = global;
for (const f of ['src/js/data/geodata_nagpur.js', 'src/js/data/geodata.js', 'src/js/core.js', 'src/js/engine/scenarios.js', 'src/js/engine/engine.js',
  'src/js/engine/interventions.js', 'src/js/engine/analytics.js', 'src/js/engine/comms.js', 'src/js/engine/redteam.js'])
  vm.runInThisContext(fs.readFileSync(path.join(ROOT, f), 'utf8'), { filename: f });
const T = global.TWIN, C = T.core;
const OUT = path.join(ROOT, 'docs', 'reference');
fs.mkdirSync(OUT, { recursive: true });
const md = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const pct = (x) => (x == null || !isFinite(x) ? '—' : Math.round(x * 100) + '%');
const f2 = (x) => (x == null || !isFinite(x) ? '—' : x.toFixed(2));
const kindOf = (f) => (f.type === 'telecom' ? 'telecom' : f.subtype === 'EMS station' ? 'ems' : f.subtype === 'Pumping station' ? 'pump' : f.type);
const SYS = { drainage: 'Drainage', pump: 'Drainage (pump)', traffic: 'Roads', power: 'Power', telecom: 'Telecom', ems: 'EMS', hospital: 'Hospitals', weather: 'Weather' };
const stamp = new Date().toISOString().slice(0, 10);
const banner = (what) => `<!-- Generated by tools/gen_docs.js on ${stamp}. Do not edit by hand: re-run the script. -->\n\n`;

// ── City reference ────────────────────────────────────────────────────────
function cityDoc(id) {
  const g = global.TWIN_GEOS[id], F = g.facilities;
  const idx = Object.fromEntries(F.map((f, i) => [f.id, i]));
  const L = [];
  L.push(banner('city') + `# ${g.city} twin: complete reference\n`);
  L.push(`Everything the ${g.city} twin is built from, extracted from \`src/js/data/${id === 'raleigh' ? 'geodata.js' : 'geodata_' + id + '.js'}\` (generated by \`tools/build_data.py\` from \`tools/${id === 'raleigh' ? 'spec.py' : 'spec_' + id + '.py'}\` and OpenStreetMap tiles).\n`);
  const pop = g.population ? g.population.cells.reduce((s, c) => s + c[2], 0) : 0;
  const byKind = {};
  F.forEach((f) => { const k = kindOf(f); byKind[k] = (byKind[k] || 0) + 1; });
  L.push(`## At a glance\n`);
  L.push(`| Property | Value |\n| --- | --- |`);
  L.push(`| City, region | ${g.city}, ${g.region} |`);
  L.push(`| Time zone | ${g.tz} (${g.tzLabel}) |`);
  L.push(`| Map extent (W, S, E, N) | ${g.extent.join(', ')} |`);
  L.push(`| Centre | ${g.center.join(', ')} |`);
  L.push(`| Default camera | centre ${g.overview.center.join(', ')}, zoom ${g.overview.zoom}, pitch ${g.overview.pitch}°, bearing ${g.overview.bearing}° |`);
  L.push(`| Default clock origin (T+0) | ${g.t0} (scenarios may override it) |`);
  L.push(`| Monitored facilities | ${F.length}: ${Object.entries(byKind).map(([k, n]) => `${n} ${SYS[k]}`).join(', ')} |`);
  L.push(`| Candidate dependency links | ${g.edges.length}, of which ${g.edges.filter((e) => e.w === 0).length} are deliberately spurious (absent in the hidden world) |`);
  L.push(`| Links routed on real networks | ${g.edges.filter((e) => e.path && e.path.length > 2).length} (Dijkstra on the street graph or down the waterway graph) |`);
  L.push(`| Street corridor segments | ${g.corridors.length} (classes: ${[...new Set(g.corridors.map((c) => c.c))].join(', ')}) |`);
  L.push(`| Drainage segments | ${g.drainage.length} (main channels: ${g.drainage.filter((d) => d.m).length}) |`);
  L.push(`| Pond / basin polygons | ${(g.basins || []).length} |`);
  L.push(`| Substations in OSM (incl. unmonitored) | ${(g.substations || []).length}, with Voronoi service areas |`);
  L.push(`| Districts (labels) | ${g.districts.length} |`);
  L.push(`| Modeled population | ${pop.toLocaleString('en-US')} residents on ${g.population ? g.population.cells.length : 0} cells of ${g.population ? g.population.cell : '—'} m |`);
  L.push(`| Planted sensor faults | ${g.faults.length} |`);
  L.push(`| Planted false citizen reports | ${g.falseReports.length} |`);
  L.push('');
  const order = ['drainage', 'pump', 'traffic', 'power', 'telecom', 'ems', 'hospital', 'weather'];
  L.push(`## Facilities (${F.length})\n`);
  L.push('Tier 1 is the most consequential (weights the city index ×3), tier 3 the least (×1). `base` is the normal operating level (0–1). Drainage sites carry a capacity threshold (`cap`, antecedent rainfall in mm), a response `scale` and a catchment memory `tau` (h), and the rain gauge they read. `people` is the modeled population within 1.2 km.\n');
  for (const k of order) {
    const list = F.filter((f) => kindOf(f) === k);
    if (!list.length) continue;
    L.push(`### ${SYS[k]} (${list.length})\n`);
    L.push('| ID | Name | Kind | District | Sensor | Tier | Base | Model parameters | People ≤1.2 km | Location (lng, lat) | Source |\n| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |');
    for (const f of list) {
      const p = f.p || {};
      const extra = [p.cap != null ? `cap ${p.cap}` : '', p.scale != null ? `scale ${p.scale}` : '', p.tau != null ? `tau ${p.tau} h` : '', p.wx ? `gauge ${p.wx}` : '', f.beds ? `${f.beds} beds` : ''].filter(Boolean).join(', ') || '—';
      L.push(`| \`${f.id}\` | ${md(f.name)} | ${md(f.subtype || f.type)} | ${md(f.district)} | ${md(f.sensor)} | ${f.tier} | ${p.base ?? '—'} | ${md(extra)} | ${(f.people || 0).toLocaleString('en-US')} | ${f.lngLat.map((v) => v.toFixed(4)).join(', ')} | ${md(f.source || '')} |`);
    }
    L.push('');
  }
  L.push(`## Candidate dependency links (${g.edges.length})\n`);
  L.push('Each link is a hypothesis the twin must confirm or prune from data: `w` is its weight in the hidden ground-truth world (0 = planted fake; the forecaster never sees `w`), `lag` is the propagation delay. Grouped by the system pair it connects.\n');
  const pairs = {};
  for (const e of g.edges) {
    const a = SYS[kindOf(F[idx[e.from]])], b = SYS[kindOf(F[idx[e.to]])];
    (pairs[`${a} → ${b}`] ||= []).push(e);
  }
  L.push('| System pair | Links | Planted fakes |\n| --- | --- | --- |');
  for (const [k, list] of Object.entries(pairs).sort((x, y) => y[1].length - x[1].length)) L.push(`| ${k} | ${list.length} | ${list.filter((e) => e.w === 0).length} |`);
  L.push('');
  for (const [k, list] of Object.entries(pairs).sort((x, y) => y[1].length - x[1].length)) {
    L.push(`### ${k}\n`);
    L.push('| From | To | Mechanism | Lag (h) | Kind | Route length | Hidden weight |\n| --- | --- | --- | --- | --- | --- | --- |');
    for (const e of list) L.push(`| \`${e.from}\` ${md(F[idx[e.from]].name)} | \`${e.to}\` ${md(F[idx[e.to]].name)} | ${md(e.mechanism)} | ${e.lag} | ${md(e.kind)} | ${e.km != null ? e.km.toFixed(2) + ' km' : '—'} | ${e.w === 0 ? '**0 (planted fake)**' : e.w} |`);
    L.push('');
  }
  L.push(`## Districts (${g.districts.length})\n`);
  L.push('| Label | Location (lng, lat) |\n| --- | --- |');
  for (const d of g.districts) L.push(`| ${md(d.name)} | ${d.lngLat.map((v) => v.toFixed(4)).join(', ')} |`);
  L.push('');
  if (g.population) {
    const cells = g.population.cells.slice().sort((a, b) => b[2] - a[2]);
    L.push(`## Population grid\n`);
    L.push(`${g.population.cells.length} cells of ${g.population.cell} m, ${pop.toLocaleString('en-US')} residents in total, distributed by street, building and water density and scaled to the city total. Densest cells: ${cells.slice(0, 5).map((c) => `${c[2].toLocaleString('en-US')} at ${c[0].toFixed(3)}, ${c[1].toFixed(3)}`).join('; ')}. Median cell: ${cells[Math.floor(cells.length / 2)][2].toLocaleString('en-US')} residents.\n`);
  }
  L.push(`## Planted sensor faults (${g.faults.length})\n`);
  L.push('Applied to the observation stream only (the hidden truth is untouched). The twin is never told about them.\n');
  L.push('| Sensor | Facility | Fault | From | To | Detail |\n| --- | --- | --- | --- | --- | --- |');
  for (const x of g.faults) L.push(`| \`${x.id}\` | ${md(F[idx[x.id]] ? F[idx[x.id]].name : '?')} | ${x.kind} | T+${x.from} h | T+${x.to} h | ${md(x.note)}${x.value != null ? ` (value ${x.value})` : ''} |`);
  L.push('');
  L.push(`## Planted false citizen reports (${g.falseReports.length})\n`);
  L.push('| Time | Near | Text |\n| --- | --- | --- |');
  for (const r of g.falseReports) L.push(`| T+${r.t} h | \`${r.near}\` ${md(F[idx[r.near]] ? F[idx[r.near]].name : '')} | ${md(r.text)} |`);
  L.push('');
  fs.writeFileSync(path.join(OUT, `${id}.md`), L.join('\n'));
  console.log('wrote', id);
}

// ── Results across every city and scenario ─────────────────────────────────
function results() {
  const L = [banner('results') + '# Results: every city and scenario\n', 'Produced by running the engine headlessly on every scenario available to each city, with the same code the browser runs. Synthetic ground truth: these numbers show the pipeline works end to end and is isolated from future data; they are not evidence of real-world skill.\n'];
  const runs = [];
  for (const [city, g] of Object.entries(global.TWIN_GEOS)) {
    for (const s of Object.values(T.scenarios)) {
      if (s.cities && !s.cities.includes(city)) continue;
      C.setTZ(g.tz, g.tzLabel);
      const t0 = Date.now();
      const e = T.engine.create(g, { scenario: s.id });
      const an = T.analytics.create(e);
      const liveNow = s.liveNow || 34.5, kL = e.kOf(liveNow);
      const V = e.validation();
      const crit = Array.from({ length: e.K }, (_, k) => e.cityAt(k).counts.critical);
      const peakCrit = Math.max(...crit), kPeak = crit.indexOf(peakCrit), firstCrit = crit.findIndex((x) => x > 0);
      let crCross = null; for (let k = 0; k < e.K; k++) if (an.cascadeR(k).r >= 1) { crCross = k * e.DT; break; }
      const crPeak = Math.max(...Array.from({ length: e.K }, (_, k) => an.cascadeR(k).r));
      const fcCross = an.crossing(kL);
      const pl = T.interventions.create(e);
      const singles = pl.CATALOG.map((a) => ({ a, r: pl.evaluate(kL, [a.id], 16) }));
      const ids = pl.recommend(kL, 5);
      const ev = ids.length ? pl.evaluate(kL, ids, 32) : null;
      const dl = ids.length ? pl.deadline(kL, ids, 24, 2) : null;
      const crisesL = an.crises(kL).list, crisesP = an.crises(kPeak).list;
      const atk = T.redteam.attacks(e);
      const kNow = Math.min(e.K - 1, kL + 12), tA = Math.max(0.5, kNow * e.DT - 6);
      const red = atk.map((a) => {
        const att = T.engine.create(g, { scenario: s.id, script: T.redteam.merge(atk, [a.id], tA) });
        return { a, s: T.redteam.score(e, att, atk, [a.id], tA, kNow) };
      });
      const stF = an.crises(kL);
      runs.push({ city, g, s, e, V, peakCrit, kPeak, firstCrit, crCross, crPeak, fcCross, singles, ids, ev, dl, crisesL, crisesP, red, liveNow, kL, kNow, tA, stF });
      console.log('ran', city, s.id, Date.now() - t0, 'ms');
    }
  }
  L.push('## Scorecard\n');
  L.push('Warning rule: P(critical within 24 h) ≥ 60%. "Events" are facilities that truly reached CRITICAL. Brier and skill are computed over P(critical within 6, 12 and 24 h) issued every hour.\n');
  L.push('| City | Scenario | Median lead | Detection | False alarms | Brier | Skill vs climatology | Events | Forecasts scored |\n| --- | --- | --- | --- | --- | --- | --- | --- | --- |');
  for (const r of runs) { const v = r.V, few = v.events < 3; L.push(`| ${r.g.city} | ${md(r.s.label)} | ${few ? '—' : v.medianLead.toFixed(1) + ' h'} | ${few ? '—' : `${pct(v.pod)} (${v.hits}/${v.events})`} | ${few ? '—' : `${pct(v.far)} (${v.falseAlarms}/${v.alarms})`} | ${v.brier.toFixed(3)} | ${few || !isFinite(v.bss) ? 'too few events' : (v.bss >= 0 ? '+' : '') + v.bss.toFixed(2)} | ${v.events} | ${v.pairs.toLocaleString('en-US')} |`); }
  L.push('');
  L.push('## Cascade shape\n');
  L.push('| City | Scenario | "Now" in live mode | First facility CRITICAL | Peak facilities CRITICAL | Peak at | Cascade-R crosses 1 | Peak Cascade-R | Forecast crossing issued at "now" |\n| --- | --- | --- | --- | --- | --- | --- | --- | --- |');
  for (const r of runs) L.push(`| ${r.g.city} | ${md(r.s.label)} | T+${r.liveNow} h | ${r.firstCrit >= 0 ? 'T+' + (r.firstCrit * r.e.DT).toFixed(1) + ' h' : 'none'} | ${r.peakCrit} | ${r.peakCrit ? 'T+' + (r.kPeak * r.e.DT).toFixed(1) + ' h' : '—'} | ${r.crCross != null ? 'T+' + r.crCross.toFixed(1) + ' h' : 'never'} | ${r.crPeak.toFixed(2)} | ${r.fcCross ? (r.fcCross.now ? 'already above 1' : 'T+' + r.fcCross.t.toFixed(1) + ' h') : 'not within horizon'} |`);
  L.push('');
  for (const r of runs) {
    const F = r.e.F;
    L.push(`## ${r.g.city} · ${r.s.label}\n`);
    L.push(`${md(r.s.blurb)}\n`);
    const crisisRows = (list) => list.length ? '| ID | Type | Stage | Facilities | Districts | Residents in footprint | Next CRITICAL |\n| --- | --- | --- | --- | --- | --- | --- |\n' + list.map((c) => `| \`${c.id}\` | ${c.type} | ${c.stage} | ${c.members.length} | ${md(c.districts.slice(0, 6).join(', '))}${c.districts.length > 6 ? ` +${c.districts.length - 6}` : ''} | ${Math.round(c.people).toLocaleString('en-US')} | ${c.nextCrit ? `${md(F[c.nextCrit.i].name)} at T+${c.nextCrit.t.toFixed(1)} (${pct(c.nextCrit.prob)})` : '—'} |`).join('\n') : '_No facility at or forecast to reach HIGH RISK within 24 h._';
    L.push(`**Crises at "now" (T+${r.liveNow} h):** ${r.crisesL.length}\n\n${crisisRows(r.crisesL)}\n`);
    L.push(`**Crises at the peak (T+${(r.kPeak * r.e.DT).toFixed(1)} h):** ${r.crisesP.length}\n\n${crisisRows(r.crisesP)}\n`);
    const links = r.stF.links;
    if (links.length) L.push(`Interactions at "now": ${links.map((l) => l.kind === 'couples' ? `${r.stF.list[l.from].id} can propagate into ${r.stF.list[l.to].id} via ${F[r.e.E[l.edge].from].id} → ${F[r.e.E[l.edge].to].id}` : `${r.stF.list[l.from].id} and ${r.stF.list[l.to].id} both load ${F[l.fac].name}`).join('; ')}.\n`);
    L.push(`**Action catalogue at "now"** (${r.singles.length} actions; each evaluated alone on 16 futures):\n`);
    L.push('| Action | Crews | Detail | Side effect | Alone: critical facility-hours |\n| --- | --- | --- | --- | --- |');
    for (const { a, r: x } of r.singles) L.push(`| ${md(a.label)} (\`${a.id}\`) | ${a.cost} | ${md(a.detail)} | ${md(a.side || '—')} | ${x.reduction >= 0 ? '−' : '+'}${Math.abs(x.reduction * 100).toFixed(1)}% |`);
    L.push('');
    if (r.ev) {
      L.push(`**Recommended plan within 5 crews:** ${r.ids.map((id) => r.singles.find((x) => x.a.id === id).a.label).join('; ')}. Expected ${pct(r.ev.reduction)} fewer critical facility-hours (${r.ev.base.critHours.toFixed(0)} → ${r.ev.with.critHours.toFixed(0)}), hospital critical hours ${r.ev.base.careHours.toFixed(1)} → ${r.ev.with.careHours.toFixed(1)}, P(a hospital goes critical) ${pct(r.ev.base.hospCrit)} → ${pct(r.ev.with.hospCrit)}${r.ev.cascadeBroken ? ' (cascade broken)' : ''}.`);
      if (r.dl) L.push(`Decision deadline: ${r.dl.actBy != null && r.dl.actBy > 0 ? `start by T+${(r.liveNow + r.dl.actBy).toFixed(1)} h to keep 80% of the benefit` : 'act immediately; the benefit decays with any delay'}${r.dl.half != null ? `; worth less than half by T+${(r.liveNow + r.dl.half).toFixed(1)} h` : ''}. Benefit by start delay: ${r.dl.pts.map((p) => `+${p.h} h ${Math.round(p.reduction * 100)}%`).join(', ')}.`);
      if (r.ev.sideEffects.length) L.push(`Side effects: ${r.ev.sideEffects.map((s) => `${F[s.i].name} peak +${Math.round(s.delta * 100)} pts`).join('; ')}.`);
      L.push('');
    } else L.push('**Recommended plan:** none; no action reduces expected critical facility-hours at this time.\n');
    L.push(`**Red team** (each attack alone, starting T+${r.tA.toFixed(1)} h, scored at T+${(r.kNow * r.e.DT).toFixed(1)} h against the clean run):\n`);
    L.push('| Attack | Target | Outcome | Raw feed vs truth | Twin vs truth | False alerts | Delayed alerts | Nowcast error (clean → attacked) |\n| --- | --- | --- | --- | --- | --- | --- | --- |');
    for (const { a, s } of r.red) {
      const row = s.rows[0] || {};
      let outcome = '', raw = '—', twin = '—';
      if (row.kind === 'sensor') { outcome = row.masked ? 'masked' : row.harmless ? `no effect (stayed within ${Math.round(row.dev * 100)} pts)` : row.flaggedAfter != null ? `flagged after ${row.flaggedAfter.toFixed(1)} h` : 'not flagged'; if (!row.masked) { raw = `${pct(row.raw)} vs ${pct(row.truth)}`; twin = `${pct(row.twin)} vs ${pct(row.truth)}`; } }
      else if (row.kind === 'reports') outcome = `${row.held} of ${row.n} posts held (median corroboration ${pct(row.median)})`;
      else if (row.kind === 'blackout') outcome = `${row.dark} of ${row.total} feeds dark; ESS ${Math.round(row.essClean)} → ${Math.round(row.essAtt)}`;
      L.push(`| ${md(a.label)} | ${a.targets.map((i) => '`' + F[i].id + '`').join(', ') || 'all feeds'} | ${md(outcome)} | ${raw} | ${twin} | ${s.extraAlerts.length} | ${s.delayedAlerts.length} | ${s.maeClean.toFixed(3)} → ${s.maeAtt.toFixed(3)} |`);
    }
    L.push('');
  }
  fs.writeFileSync(path.join(OUT, 'results.md'), L.join('\n'));
  console.log('wrote results');
  return runs;
}

// ── Messages: templates and real generated samples ─────────────────────────
function messages() {
  const L = [banner('messages') + '# Communications: templates and generated samples\n'];
  L.push('The communications desk writes three products from the engine state at the issue time. Templates are per hazard family and language; areas, times, probabilities and helpline numbers are filled from the twin. Source: `src/js/engine/comms.js`.\n');
  L.push('## Per-city configuration\n');
  L.push('| City | Languages | Locales | Helpline | Ambulance | Issuing desk |\n| --- | --- | --- | --- | --- | --- |');
  for (const [id, g] of Object.entries(global.TWIN_GEOS)) { const c = T.comms.cityCfg(g); L.push(`| ${g.city} | ${c.langs.map((l) => T.comms.LANG_NAME[l]).join(', ')} | ${Object.values(c.locale).join(', ')} | ${c.help} | ${c.ems} | ${c.desk} |`); }
  L.push('');
  L.push('## Hazard families and CAP vocabulary\n');
  L.push('| Family | Crisis type | CAP category | CAP response type |\n| --- | --- | --- | --- |');
  const cat = { flood: 'Met', grid: 'Infra', toxic: 'CBRNE', crowd: 'Safety', gridlock: 'Transport', health: 'Health', comms: 'Infra' };
  const resp = { flood: 'Prepare (Evacuate when Extreme)', grid: 'Prepare', toxic: 'Shelter', crowd: 'Avoid', gridlock: 'Avoid', health: 'Monitor', comms: 'Prepare' };
  for (const [k, v] of Object.entries(T.analytics.FAMILY_LABEL)) L.push(`| ${k} | ${v} | ${cat[k]} | ${resp[k]} |`);
  L.push('');
  L.push('## Message templates (headline · advice)\n');
  for (const [lang, fams] of Object.entries(T.comms.TXT)) {
    L.push(`### ${T.comms.LANG_NAME[lang]} (\`${lang}\`)\n`);
    L.push('| Family | Headline | Advice |\n| --- | --- | --- |');
    for (const [fam, [h, a]] of Object.entries(fams)) L.push(`| ${fam} | ${md(h)} | ${md(a)} |`);
    L.push('');
  }
  // Generated samples: Nagpur monsoon at T+47
  const g = global.TWIN_GEOS.nagpur;
  C.setTZ(g.tz, g.tzLabel);
  const e = T.engine.create(g, { scenario: 'monsoon2023' });
  const an = T.analytics.create(e);
  const k = e.kOf(47);
  const X = an.crises(k);
  const c = X.list[0];
  L.push('## Generated sample: Nagpur monsoon replay, issued at T+47.0 h (23 Sep 2023, 05:00 IST)\n');
  L.push('### Public SMS for the largest crisis\n');
  L.push('| Language | Encoding | Characters | Segments | Text |\n| --- | --- | --- | --- | --- |');
  for (const lang of T.comms.cityCfg(g).langs) { const s = T.comms.sms(g, e.t0, c, k * e.DT, lang); L.push(`| ${T.comms.LANG_NAME[lang]} | ${s.encoding} | ${s.chars} | ${s.segments} | ${md(s.text)} |`); }
  L.push('');
  L.push('### CAP 1.2 alert\n\n```xml\n' + T.comms.cap(null, e, c, k, { cascadeR: an.cascadeR(k).r }).trim() + '\n```\n');
  const pl = T.interventions.create(e);
  const ids = pl.recommend(k, 5);
  const plan = ids.length ? { ids, result: pl.evaluate(k, ids), deadline: pl.deadline(k, ids, 16, 2), catalog: pl.CATALOG } : null;
  const people = { high: 0, crit: 0 };
  L.push('### Situation report\n\n```text\n' + T.comms.sitrep(null, e, k, { number: `No. ${Math.floor(47 / 3) + 1}`, cr: an.cascadeR(k), crises: X, people, plan, redTeam: false }) + '\n```\n');
  L.push('_In the browser the "people at risk" line is filled from the population layer; this headless sample leaves it at zero._\n');
  fs.writeFileSync(path.join(OUT, 'messages.md'), L.join('\n'));
  console.log('wrote messages');
}

cityDoc('nagpur');
